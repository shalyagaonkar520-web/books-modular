"""Regenerate docs/erd/*.md (Mermaid ERDs) and docs/api/*.json (OpenAPI) from the code.

Run from the repo root with each service's dependencies installed:

    python scripts/gen_docs.py books    # uses apps/books
    python scripts/gen_docs.py core
    python scripts/gen_docs.py bookings

The output is committed so reviewers see schema and API changes in the diff.
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

SERVICES = {
    "books": {"path": ROOT / "apps" / "books", "db": "backend.db", "models": "backend.models", "app": "backend.main", "title": "Rooman Books"},
    "core": {"path": ROOT / "core" / "backend", "db": "core_api.db", "models": None, "app": "core_api.main", "title": "Rooman One Core"},
    "bookings": {"path": ROOT / "apps" / "bookings" / "backend", "db": "bookings_api.db", "models": None, "app": "bookings_api.main", "title": "Rooman Bookings"},
}


def _mermaid_type(column) -> str:
    try:
        name = column.type.python_type.__name__
    except NotImplementedError:
        name = type(column.type).__name__
    return {"str": "string", "int": "int", "bool": "bool", "Decimal": "decimal", "datetime": "datetime", "date": "date"}.get(name, name.lower())


def erd(metadata, title: str) -> str:
    lines = [f"# {title}: entity diagram", "", "Generated by `scripts/gen_docs.py` from the SQLAlchemy models. Do not edit by hand.", ""]
    if not metadata.tables:
        lines += ["No tables yet.", ""]
        return "\n".join(lines)
    lines += ["```mermaid", "erDiagram"]
    for table in sorted(metadata.tables.values(), key=lambda t: t.name):
        lines.append(f"    {table.name} {{")
        for column in table.columns:
            keys = []
            if column.primary_key:
                keys.append("PK")
            if column.foreign_keys:
                keys.append("FK")
            lines.append(f"        {_mermaid_type(column)} {column.name}{' ' + ','.join(keys) if keys else ''}")
        lines.append("    }")
    for table in sorted(metadata.tables.values(), key=lambda t: t.name):
        for fk in sorted(table.foreign_keys, key=lambda f: f.parent.name):
            target = fk.column.table.name
            optional = "o" if fk.parent.nullable else "|"
            lines.append(f'    {target} ||--{optional}{{ {table.name} : "{fk.parent.name}"')
    lines += ["```", ""]
    tenant = sorted(t.name for t in metadata.tables.values() if "organization_id" in t.columns or "org_id" in t.columns)
    lines += [f"Tables carrying the tenant column ({len(tenant)} of {len(metadata.tables)}): " + ", ".join(f"`{t}`" for t in tenant), ""]
    return "\n".join(lines)


def main(name: str) -> None:
    service = SERVICES[name]
    os.chdir(service["path"])
    sys.path.insert(0, str(service["path"]))
    tmp = tempfile.mkdtemp(prefix="gen-docs-")
    os.environ.setdefault("DATABASE_URL", f"sqlite:///{tmp}/docs.db")
    os.environ.setdefault("SECRET_KEY", "docs-generation-only")
    os.environ.setdefault("ENVIRONMENT", "development")

    import importlib

    db = importlib.import_module(service["db"])
    if service["models"]:
        importlib.import_module(service["models"])
    app = importlib.import_module(service["app"]).app

    (ROOT / "docs" / "erd").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "api").mkdir(parents=True, exist_ok=True)
    (ROOT / "docs" / "erd" / f"{name}.md").write_text(erd(db.Base.metadata, service["title"]), encoding="utf-8")
    (ROOT / "docs" / "api" / f"{name}.openapi.json").write_text(json.dumps(app.openapi(), indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"{name}: {len(db.Base.metadata.tables)} tables, {len(app.openapi().get('paths', {}))} paths")


if __name__ == "__main__":
    if len(sys.argv) != 2 or sys.argv[1] not in SERVICES:
        sys.exit(f"usage: python scripts/gen_docs.py {{{'|'.join(SERVICES)}}}")
    main(sys.argv[1])
