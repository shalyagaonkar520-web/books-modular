NL, CRLF = "\n", "\r\n"


def main(texts: dict = TEXTS) -> None:
    for path in FILES:
        raw = path.read_bytes().decode("utf-8")
        crlf = CRLF in raw
        text = raw.replace(CRLF, NL)
        existing = json.loads(text)["texts"]
        new = {key: value for key, value in texts.items() if key not in existing}
        if new:
            # Appended as one block at the end of "texts" (the document's last
            # member), keeping the file's blank-line grouping untouched.
            end = text.rstrip().rindex(NL + "  }")
            entries = [f"    {json.dumps(k)}: {json.dumps(v, ensure_ascii=False)}" for k, v in new.items()]
            text = text[:end] + "," + NL + NL + ("," + NL).join(entries) + text[end:]
            json.loads(text)
        out = text.replace(NL, CRLF) if crlf else text
        path.write_bytes(out.encode("utf-8"))
        print(f"{path.relative_to(ROOT)}: +{len(new)} texts")


if __name__ == "__main__":
    main()
